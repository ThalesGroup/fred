Lang = Literal["fr", "en"]


@dataclass(frozen=True)
class AgentLabels:
    singular: str = "Agent"
    plural: str = "Agents"

    def render(self, value: str) -> str:
        def safe(label: str, fallback: str) -> str:
            label = re.sub(r"[\x00-\x1f\x7f]", "", label).strip() or fallback
            return "'" + label if label.startswith(("=", "+", "-", "@")) else label

        singular, plural = safe(self.singular, "Agent"), safe(self.plural, "Agents")
        labels = {
            "agentsNicknameSingular": singular,
            "agentsNicknamePlural": plural,
            "agentsNicknameSingularLowercase": singular.lower(),
            "agentsNicknamePluralLowercase": plural.lower(),
        }
        for key, label in labels.items():
            value = value.replace("{{" + key + "}}", label)
        return value


