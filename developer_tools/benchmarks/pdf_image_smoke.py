"""Exercise real PDF/OCR/PPTX processors and startup configuration in a built image.

Usage: python pdf_image_smoke.py /corpus [--pymupdf]
Requires the corpus generated by pdf_ingestion.py and models shipped in the image.
No database, model gateway or Temporal service is contacted. Full service lifespan
and persistence checks belong to deployment integration tests.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import shutil
import sys
import tempfile
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from contextlib import redirect_stdout
from pathlib import Path

import yaml


def run(corpus: Path, optional: bool) -> dict:
    from knowledge_flow_backend.application_context import ApplicationContext
    from knowledge_flow_backend.core.processors.input.lightweight_markdown_processor.lite_pdf_to_md_processor import (
        LitePdfMarkdownProcessor,
    )
    from knowledge_flow_backend.core.processors.input.pdf_markdown_processor.docling_processor import (
        DoclingPdfExtractor,
    )
    from knowledge_flow_backend.core.processors.input.pptx_markdown_processor.utils.pptx_slide_renderer import (
        render_pdf_pages_to_png,
    )
    from knowledge_flow_backend.main import create_app
    from knowledge_flow_backend.main_worker import main as worker_main

    with tempfile.TemporaryDirectory() as work:
        folder = Path(work)
        raw = yaml.safe_load(Path("/config/configuration_worker.yaml").read_text())
        raw["processing"]["path_base_model"] = "/app"
        raw["scheduler"]["enabled"] = False
        raw["observability"]["kpi"]["opensearch"] = {"enabled": False}
        raw["observability"]["kpi"]["prometheus"]["enabled"] = False
        raw["storage"]["log_store"] = None
        raw["content_storage"] = {"type": "local", "root_path": str(folder / "content")}
        raw["filesystem"] = {"type": "local", "root": str(folder / "filesystem")}
        raw["storage"]["vector_store"] = {"type": "in_memory"}
        for profile in raw["processing"]["profiles"].values():
            profile["process_images"] = False
            profile["generate_summary"] = False
            if optional:
                for processor in profile["input_processors"]:
                    processor["class_path"] = processor["class_path"].replace(
                        "lite_pdf_to_md_processor", "lite2_pdf_to_md_processor"
                    )
        if optional:
            raw["processing"]["profiles"]["rich"]["pdf"]["extractor"] = "pymupdf"
        config_file = folder / "configuration.yaml"
        config_file.write_text(yaml.safe_dump(raw))
        os.environ["CONFIG_FILE"] = str(config_file)
        # Placeholder credentials are never used: this smoke test has no remote calls.
        os.environ["OPENAI_API_KEY"] = "unused-image-smoke"
        os.environ["OPENSEARCH_PASSWORD"] = "unused-image-smoke"
        os.environ["FRED_POSTGRES_PASSWORD"] = "unused-image-smoke"
        app = create_app()
        assert app.routes
        ApplicationContext._instance = None
        asyncio.run(worker_main())
        report = {
            "startup": "API factory and scheduler-disabled worker; no service lifespan",
            "files": {},
        }
        manifest = json.loads((corpus / "manifest.json").read_text())
        fast = LitePdfMarkdownProcessor()
        if optional:
            from knowledge_flow_backend.core.processors.input.lightweight_markdown_processor.lite2_pdf_to_md_processor import (
                LitePdfMarkdownProcessor as OptionalProcessor,
            )

            fast = OptionalProcessor()
        docling = DoclingPdfExtractor(num_threads=2)

        def ingest(record: dict) -> tuple[str, dict]:
            source = corpus / record["file"]
            output = folder / source.stem
            output.mkdir(exist_ok=True)
            if record["kind"] == "pptx":
                from fred_core.conversion import convert_office_file_to_pdf

                local_source = output / source.name
                shutil.copyfile(source, local_source)
                pdf = convert_office_file_to_pdf(local_source)
                assert pdf is not None
                images = render_pdf_pages_to_png(pdf, [1, 2, 3, 999], output)
                assert set(images) == {1, 2, 3}
                from PIL import Image, ImageChops

                for image_path in images.values():
                    with Image.open(image_path) as image:
                        assert image.size == (1440, 1080)
                        assert image.mode == "RGB"
                        assert ImageChops.difference(
                            image.crop((100, 100, 1200, 400)),
                            Image.new("RGB", (1100, 300), "white"),
                        ).getbbox()
                        if source.stem == "slides-mixed":
                            assert image.getpixel((650, 650)) == (0, 0, 255)
                return source.name, {
                    "slides": len(images),
                    "size": [1440, 1080],
                    "text_and_graphics": True,
                }
            if record["kind"] == "ocr" or source.stem in {"table", "columns"}:
                text, images = docling.extract(source, str(output))
                wanted = Counter(" ".join(record["pages"]).split())
                actual = Counter(text.split())
                recall = sum((wanted & actual).values()) / sum(wanted.values())
                if record["kind"] == "ocr":
                    assert recall >= 0.95, (source, recall, text)
                    for number in range(1, len(record["pages"]) + 1):
                        assert f"ANCHOR{number}" in text
                else:
                    rows = [
                        [cell.strip() for cell in line.strip("|").split("|")]
                        for line in text.splitlines()
                        if "|" in line
                    ]
                    for expected in (
                        ("A12", "456", "Ready"),
                        ("B34", "789", "Waiting"),
                    ):
                        assert any(
                            all(cell in row for cell in expected) for row in rows
                        ), (source, expected, text)
                return source.name, {
                    "recall": recall,
                    "text": text,
                    "images": len(images),
                }
            converted = fast.convert_file_to_markdown(source, output, source.stem)
            text = Path(converted["md_file"]).read_text(encoding="utf-8")
            assert text
            return source.name, {"chars": len(text)}

        # Production isolates fast extraction jobs in separate processes. Do not
        # invent concurrent PyMuPDF calls in one interpreter for this smoke test.
        fast_records = [
            record
            for record in manifest
            if record["kind"] == "text"
            and Path(record["file"]).stem not in {"table", "columns"}
        ]
        mixed_records = [record for record in manifest if record not in fast_records]
        report["files"] = dict(map(ingest, fast_records))
        # Mix Docling and slide rendering in the same worker with real models.
        with ThreadPoolExecutor(max_workers=4) as pool:
            report["files"].update(pool.map(ingest, mixed_records))
        if optional:
            from knowledge_flow_backend.core.processors.input.pdf_markdown_processor.pymupdf_processor import (
                PyMuPdfExtractor,
            )

            text, _ = PyMuPdfExtractor().extract(corpus / "text.pdf", str(folder))
            assert "ANCHOR1" in text
            report["advanced_optional"] = "pymupdf"
        return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("corpus", type=Path)
    parser.add_argument("--pymupdf", action="store_true")
    args = parser.parse_args()
    with redirect_stdout(sys.stderr):
        result = run(args.corpus, args.pymupdf)
    print(json.dumps(result, indent=2))
